import { expect, test } from '@playwright/test';

test.use({ locale: 'en-GB' });
for (const [width, height] of [[1440, 900], [390, 844]]) {
  test(`real onboarded contexts: canonical navigation and shot interaction ${width}x${height}`, async ({ page }) => {
    test.setTimeout(60_000);
    await page.setViewportSize({ width, height });
    const catalog = await (await page.request.get('/api/v1/competitions')).json();
    expect(catalog.competitions).toEqual([{ competition_id: 9 }, { competition_id: 43 }]);
    const seasons = await (await page.request.get('/api/v1/competitions/9/seasons')).json();
    expect(seasons.seasons).toEqual([{ season_id: 281 }]);
    const context = '/competitions/9/seasons/281';
    const list = await (await page.request.get(`/api/v1${context}/matches`)).json();
    expect(list.matches).toHaveLength(34);
    const [first, second] = list.matches;
    const path = `${context}/matches/${first.match_id}`;
    const analysis = await (await page.request.get(`/api/v1${path}/analysis`)).json();
    expect(analysis.shots.length).toBeGreaterThan(0);
    const errors: string[] = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(path);
    await expect(page.getByTestId('match-header')).toContainText(first.home_team_name);
    await expect(page.locator('.comparison')).toBeVisible();
    await expect(page.locator('.race-svg')).toBeVisible();
    await expect(page.locator('.pitch-svg')).toBeVisible();
    await expect(page.locator('tbody tr').first()).toBeVisible();
    await expect(page.getByTestId('shootout-panel')).toHaveCount(0);
    await expect(page.getByTestId('shot-marker')).toHaveCount(analysis.shots.length);
    await expect(page.getByTestId('race-point')).toHaveCount(analysis.shots.length);
    expect(analysis.xg_race).toHaveLength(2 * analysis.shots.length);
    await expect(page.getByRole('combobox', { name: 'Competition', exact: true })).toHaveValue('9');
    await expect(page.getByRole('combobox', { name: 'Season', exact: true })).toHaveValue('281');
    const point = page.getByTestId('race-point').first();
    const id = await point.getAttribute('data-event-id');
    await point.focus();
    await point.press('Enter');
    await expect(page.locator(`[data-testid="shot-marker"][data-event-id="${id}"]`)).toHaveAttribute('data-state', 'selected');
    await expect(page.getByTestId('shot-details')).toContainText('Selected shot');
    await page.getByRole('combobox', { name: 'Squad coverage' }).selectOption('all');
    await expect(page.locator('tbody tr')).toHaveCount(analysis.players.length);
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    await page.screenshot({ path: `test-results/stage6b2-${width}.png`, fullPage: true });
    await page.reload();
    await expect(page).toHaveURL(path);
    await expect(page.getByTestId('match-header')).toContainText(first.home_team_name);
    await page.getByRole('combobox', { name: 'Explore a match' }).click();
    await page.locator(`[role="option"][data-match-id="${second.match_id}"]`).click();
    await expect(page).toHaveURL(`${context}/matches/${second.match_id}`);
    await expect(page.getByTestId('match-header')).toContainText(second.home_team_name);
    await page.goBack();
    await expect(page).toHaveURL(path);
    await expect(page.getByTestId('match-header')).toContainText(first.home_team_name);
    await page.goForward();
    await expect(page).toHaveURL(`${context}/matches/${second.match_id}`);
    await page.getByRole('combobox', { name: 'Competition', exact: true }).selectOption('43');
    await expect(page).toHaveURL(/\/competitions\/43\/seasons\/106\/matches\/\d+$/);
    await expect(page.getByTestId('match-header')).toBeVisible();
    await page.getByRole('combobox', { name: 'Competition', exact: true }).selectOption('9');
    await expect(page).toHaveURL(path);
    await expect(page.getByTestId('match-header')).toContainText(first.home_team_name);
    expect(errors).toEqual([]);
  });
}
